#!/usr/bin/env python3
"""Writes the dark mode's image filters (site/layouts/partials/dark-filters.html).

Each filter maps the greys like invert(p) hue-rotate(180deg), the page's white to the dark
background, and also maps the light peach to the dark one, which an invert keeps too dull.
The colours are those of site/static/css/style.css; run again after changing one of them.
"""

from pathlib import Path

PEACH = "#fbcba4"  # --color-highlight
DARK_PEACH = "#a0562a"  # its dark-mode value
# The inversion of each filter: the images' white becomes #1e1e1e, the covers' #222222.
FILTERS = {"dark-images": 225 / 255, "dark-covers": 221 / 255}

OUT = Path(__file__).resolve().parent.parent / "site/layouts/partials/dark-filters.html"


def rgb(hex_colour):
    return [int(hex_colour[i : i + 2], 16) / 255 for i in (1, 3, 5)]


def matrix(p):
    """The feColorMatrix values: A·c + b with A = H·(1−2p) + d·vᵀ and b = p, where H is
    hue-rotate(180deg), v ⟂ (1,1,1) (so the greys stay) and v·peach = 1."""
    hue = [
        [-0.574, 1.430, 0.144],
        [0.426, 0.430, 0.144],
        [0.426, 1.430, -0.856],
    ]
    peach, target = rgb(PEACH), rgb(DARK_PEACH)
    mean = sum(peach) / 3
    off_grey = [c - mean for c in peach]
    v = [c / sum(x * x for x in off_grey) for c in off_grey]
    mapped = [p + (1 - 2 * p) * sum(h * c for h, c in zip(row, peach)) for row in hue]
    d = [t - m for t, m in zip(target, mapped)]
    rows = [
        [(1 - 2 * p) * hue[i][j] + d[i] * v[j] for j in range(3)] + [0, p] for i in range(3)
    ]
    return " ".join(f"{x:.5f}" for row in rows for x in row) + " 0 0 0 1 0"


def main():
    filters = "".join(
        f'<filter id="{name}" color-interpolation-filters="sRGB">'
        f'<feColorMatrix type="matrix" values="{matrix(p)}"/></filter>'
        for name, p in FILTERS.items()
    )
    OUT.write_text(
        "{{- /* The dark mode's image filters (--image-filter, --cover-filter in style.css),\n"
        "  generated by tools/dark_filter.py. Not display:none, which would disable them. */ -}}\n"
        '<svg class="filters" width="0" height="0" aria-hidden="true" focusable="false">'
        f"{filters}</svg>\n"
    )


if __name__ == "__main__":
    main()
