"""The themes of the Nachlass Map (tools/map/map.py).

Each theme is a family of terms that Wittgenstein's remarks on a subject use. A remark
counts as evidence for a theme if it contains one of its terms (or, for Mathematics and
Logic, one of their kinds of formal notation); see README.md for how the themes were chosen
and how the shade of a remark is computed.

Terms are regular expressions, matched case-insensitively against whole words, unless
prefixed with:
  C:  case-sensitive whole word (Gewissen, the noun, but not gewissen, "certain")
  P:  phrase, matched in the running text (lowercased): "einer Regel folgen"
  PC: phrase, case-sensitive: "das Ich" (the noun, not the relative pronoun)

English terms are included for the documents Wittgenstein wrote or dictated in English.
Themes are listed by size (the number of remarks with evidence).
"""

